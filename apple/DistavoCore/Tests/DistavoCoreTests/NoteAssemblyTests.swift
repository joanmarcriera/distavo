import XCTest
@testable import DistavoCore

/// NoteAssembly fixes the section order: frontmatter, body (incl. Key moments),
/// Tracked terms, provenance footer. Defaults must be byte-identical to `body + footer`.
final class NoteAssemblyTests: XCTestCase {

    private let utc = TimeZone(identifier: "UTC")!
    private let body = "# Meeting notes\n\n## Executive summary\nWe agreed.\n\n## Key moments\n- 00:10 start\n"
    private let footer = "\n---\n_Generated by Distavo_\n"
    private let turns = [TrackedTerms.Turn(seconds: 75, speaker: "Ana", text: "The budget is tight this quarter.")]

    func testDefaultsReturnBodyPlusFooterUnchanged() {
        let out = NoteAssembly.assemble(.init(body: body, footer: footer), notes: NotesConfig(), timeZone: utc)
        XCTAssertEqual(out, body + footer)
    }

    func testTrackedTermsSitBetweenBodyAndFooter() {
        let out = NoteAssembly.assemble(.init(body: body, footer: footer, turns: turns),
                                        notes: NotesConfig(trackedTerms: ["budget"]), timeZone: utc)
        let key = out.range(of: "## Key moments")!
        let tracked = out.range(of: "## Tracked terms")!
        let foot = out.range(of: "_Generated by Distavo_")!
        XCTAssertLessThan(key.lowerBound, tracked.lowerBound)
        XCTAssertLessThan(tracked.lowerBound, foot.lowerBound)
        XCTAssertTrue(out.contains("**budget**"))
        XCTAssertTrue(out.hasSuffix(footer))
    }

    func testTermAbsentFromTranscriptAddsNoSection() {
        let out = NoteAssembly.assemble(.init(body: body, footer: footer, turns: turns),
                                        notes: NotesConfig(trackedTerms: ["kubernetes"]), timeZone: utc)
        XCTAssertEqual(out, body + footer)
    }

    func testFrontmatterComesFirstAndSectionsKeepOrder() {
        let date = Date(timeIntervalSince1970: 1_792_000_000)
        var inputs = NoteAssembly.Inputs(body: body, footer: footer, title: "Budget sync", turns: turns,
                                         meetingDate: date, sourceName: "rec.wav", durationSeconds: 125)
        inputs.llmTags = ["finance"]
        let out = NoteAssembly.assemble(inputs, notes: NotesConfig(frontmatter: true, trackedTerms: ["budget"]),
                                        timeZone: utc)
        XCTAssertTrue(out.hasPrefix("---\n"))
        let close = out.range(of: "\n---\n", range: out.index(out.startIndex, offsetBy: 4)..<out.endIndex)!
        let fm = String(out[..<close.upperBound])
        XCTAssertTrue(fm.contains("meeting"))
        XCTAssertTrue(fm.contains("finance"))
        XCTAssertTrue(fm.contains("budget"))
        let rest = String(out[close.upperBound...])
        XCTAssertLessThan(rest.range(of: "## Executive summary")!.lowerBound, rest.range(of: "## Key moments")!.lowerBound)
        XCTAssertLessThan(rest.range(of: "## Key moments")!.lowerBound, rest.range(of: "## Tracked terms")!.lowerBound)
        XCTAssertLessThan(rest.range(of: "## Tracked terms")!.lowerBound, rest.range(of: "Generated by Distavo")!.lowerBound)
    }

    func testBodyCarryingItsOwnFrontmatterIsNotDoubled() {
        let doubled = "---\ntitle: stray\n---\n" + body
        let out = NoteAssembly.assemble(.init(body: doubled, footer: footer), notes: NotesConfig(frontmatter: true),
                                        timeZone: utc)
        XCTAssertEqual(out.components(separatedBy: "title: stray").count - 1, 0)
        XCTAssertEqual(out.components(separatedBy: "\n---\n").count - 1 >= 1, true)
    }

    func testMergeAttendeesIsCaseInsensitiveAndKeepsBaseOrder() {
        XCTAssertEqual(NoteAssembly.mergeAttendees(["Ana", "Marc"], ["marc", "Joe", "joe"]), ["Ana", "Marc", "Joe"])
        XCTAssertEqual(NoteAssembly.mergeAttendees(["Ana"], []), ["Ana"])
    }

    func testMinutesRoundsAndNeverReturnsZeroForAudio() {
        XCTAssertEqual(NoteAssembly.minutes(125), 2)
        XCTAssertEqual(NoteAssembly.minutes(5), 1)
        XCTAssertNil(NoteAssembly.minutes(0))
        XCTAssertNil(NoteAssembly.minutes(-3))
        XCTAssertNil(NoteAssembly.minutes(.nan))
        XCTAssertNil(NoteAssembly.minutes(.infinity))
    }

    func testDurationIsTheLastSegmentEnd() {
        XCTAssertNil(NoteAssembly.durationSeconds(of: nil))
        let s = TranscriptSegments(segments: [
            .init(start: 0, end: 4, text: "a"), .init(start: 4, end: 9.5, text: "b")])
        XCTAssertEqual(NoteAssembly.durationSeconds(of: s), 9.5)
    }
}
