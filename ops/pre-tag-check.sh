#!/usr/bin/env bash
#
# Pre-tag check for a Distavo release (Vikunja #2679): the local stand-in for the CI
# signal that does not exist because .github/workflows/ci.yml is workflow_dispatch only.
# Run it on the commit you are about to tag. It never tags, pushes, bumps or uploads.
#
# Usage:
#   ./ops/pre-tag-check.sh [--static] [--full] [vX.Y.Z]
#     (default)  static checks + DistavoCore and DistavoEmbedded tests
#     --static   static checks only (seconds, no build): tree, version, what's new, tag
#     --full     default + xcodegen + unsigned Debug build of all three editions
#                + the edition gates on the products (needs >= 15 GB free)
#     vX.Y.Z     the tag to be created; default v<MARKETING_VERSION from apple/project.yml>
#
# Read-only on the tree: `swift test` and xcodegen rewrite Package.resolved files, so their
# content is snapshotted at start and put back on exit (2026-11-09, #2679 finding of 24 Oct).
#
# Exit 0 = every check passed, 1 = at least one FAIL (all are listed), 2 = usage error.
# Optional env: BUILD_LOCK=<dir>  mkdir-lock held around --full builds (the estate drive's
#               one-build-at-a-time rule); it is removed again on exit.
#
# The gates mirror CLAUDE.md "Editions": App Store and Setapp contain no Sparkle; the App
# Store build has no Lemon Squeezy donate link and no "Run in Terminal" helper.
set -Eeuo pipefail

# Snapshot every tracked Package.resolved; restore_resolved puts them back byte for byte.
RESOLVED_SNAP="$(mktemp -d)"
RESOLVED_FILES=()
while IFS= read -r f; do
  [[ -n "$f" ]] || continue
  RESOLVED_FILES+=("$f"); mkdir -p "$RESOLVED_SNAP/$(dirname "$f")"; cp -p "$f" "$RESOLVED_SNAP/$f"
done < <(git ls-files -- '*Package.resolved' 2>/dev/null || true)
restore_resolved() {
  local f
  for f in ${RESOLVED_FILES[@]+"${RESOLVED_FILES[@]}"}; do cp -p "$RESOLVED_SNAP/$f" "$f" 2>/dev/null || true; done
  rm -rf -- "$RESOLVED_SNAP"
}
trap restore_resolved EXIT

MODE=default; TAG=""
for a in "$@"; do
  case "$a" in
    --static) MODE=static ;;
    --full)   MODE=full ;;
    v[0-9]*)  TAG="$a" ;;
    *) echo "usage: $0 [--static|--full] [vX.Y.Z]" >&2; exit 2 ;;
  esac
done

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
FAILS=0
ok()   { printf 'PASS  %s\n' "$*"; }
fail() { printf 'FAIL  %s\n' "$*"; FAILS=$((FAILS + 1)); }
check() { local what="$1"; shift; if "$@" >/dev/null 2>&1; then ok "$what"; else fail "$what"; fi; }

# --- version and tag -----------------------------------------------------------------------
VERSION="$(sed -n 's/^ *MARKETING_VERSION: *"\{0,1\}\([0-9][0-9.]*\)"\{0,1\} *$/\1/p' apple/project.yml | head -1)"
BUILD="$(sed -n 's/^ *CURRENT_PROJECT_VERSION: *"\{0,1\}\([0-9]*\)"\{0,1\} *$/\1/p' apple/project.yml | head -1)"
[[ -n "$VERSION" && -n "$BUILD" ]] || { fail "could not read MARKETING_VERSION / CURRENT_PROJECT_VERSION from apple/project.yml"; exit 1; }
TAG="${TAG:-v$VERSION}"
echo "== Distavo pre-tag check: tag $TAG, project.yml says $VERSION (build $BUILD), mode $MODE"

[[ "$TAG" == "v$VERSION" ]] && ok "tag matches MARKETING_VERSION" || fail "tag $TAG != MARKETING_VERSION v$VERSION (bump apple/project.yml first)"
git rev-parse -q --verify "refs/tags/$TAG" >/dev/null && fail "tag $TAG already exists locally" || ok "tag $TAG is free locally"
if git remote | grep -qx origin && git ls-remote --exit-code --tags origin "refs/tags/$TAG" >/dev/null 2>&1; then
  fail "tag $TAG already exists on origin"
else
  ok "tag $TAG is free on origin (or origin unreachable: re-check by hand)"
fi
[[ -z "$(git status --porcelain --untracked-files=no)" ]] && ok "no uncommitted tracked changes" || fail "tracked files are modified"
BR="$(git branch --show-current)"; echo "      on branch ${BR:-detached} @ $(git rev-parse --short HEAD)"

# --- release metadata ----------------------------------------------------------------------
WN=apple/metadata/whats-new/en-GB.txt
[[ -s "$WN" ]] && ok "What's New file present ($WN)" || fail "What's New file missing or empty ($WN)"
[[ -s "$WN" ]] && { [[ "$(wc -c <"$WN")" -le 4000 ]] && ok "What's New within the App Store 4000-char limit" || fail "What's New over 4000 chars"; }
grep -q "^## \[\?$VERSION\]\?\|$VERSION" CHANGELOG.md 2>/dev/null && ok "CHANGELOG mentions $VERSION" \
  || echo "SKIP  no CHANGELOG entry for $VERSION (changelog is generated by git-cliff at release)"

# --- source gates (no build needed) --------------------------------------------------------
# Sparkle may only be linked into the Direct target.
if awk '/^ *#/{next} /^  Distavo-AppStore:/{t=1;next} /^  Distavo-Setapp:/{t=1;next} /^  [A-Za-z]/{t=0} t && /Sparkle/{f=1} END{exit !f}' apple/project.yml; then
  fail "project.yml lists Sparkle in the App Store or Setapp target block"
else
  ok "project.yml: no Sparkle in App Store / Setapp target blocks"
fi
check "AppStore xcconfig does not define EDITION_DIRECT or DONATE_ENABLED" \
  bash -c '! grep -E "EDITION_DIRECT|DONATE_ENABLED" apple/configs/AppStore.xcconfig | grep -v "^ *//" | grep -q .'
check "Setapp xcconfig does not define EDITION_DIRECT" \
  bash -c '! grep -E "EDITION_DIRECT" apple/configs/Setapp.xcconfig | grep -v "^ *//" | grep -q .'
check "AppStore entitlements are sandboxed" grep -A1 "com.apple.security.app-sandbox" apple/Distavo-AppStore.entitlements

[[ "$MODE" == static ]] && { echo "== static only: $FAILS failure(s)"; [[ $FAILS -eq 0 ]]; exit; }

# --- tests ---------------------------------------------------------------------------------
echo "== DistavoCore tests"
(cd apple/DistavoCore && swift test 2>&1 | tail -3) && ok "DistavoCore swift test exited 0" || fail "DistavoCore tests"
echo "== DistavoEmbedded tests"
(cd apple/DistavoEmbedded && swift test 2>&1 | tail -3) && ok "DistavoEmbedded swift test exited 0" || fail "DistavoEmbedded tests"

[[ "$MODE" == full ]] || { echo "== $FAILS failure(s)"; [[ $FAILS -eq 0 ]]; exit; }

# --- three-edition build and product gates -------------------------------------------------
FREE="$(df -g / | awk 'NR==2{print $4}')"
if [[ "$FREE" -lt 15 ]]; then fail "only ${FREE} GB free; need >= 15 for --full"; echo "== $FAILS failure(s)"; exit 1; fi
if [[ -n "${BUILD_LOCK:-}" ]]; then
  mkdir "$BUILD_LOCK" 2>/dev/null || { fail "build lock $BUILD_LOCK is held; try later"; exit 1; }
  trap 'restore_resolved; rmdir "$BUILD_LOCK" 2>/dev/null || true' EXIT
fi
command -v xcodegen >/dev/null || { fail "xcodegen not installed (brew install xcodegen)"; exit 1; }
OUT="$(mktemp -d)"; trap 'restore_resolved; rm -rf -- "$OUT"; [[ -n "${BUILD_LOCK:-}" ]] && rmdir "$BUILD_LOCK" 2>/dev/null || true' EXIT
(cd apple && xcodegen generate >/dev/null) && ok "xcodegen generate" || { fail "xcodegen generate"; exit 1; }

for edition in Direct Setapp AppStore; do
  case "$edition" in Direct) scheme=Distavo ;; Setapp) scheme=Distavo-Setapp ;; AppStore) scheme=Distavo-AppStore ;; esac
  # Scheme (not -xcconfig) selects the edition; the App Store scheme has its own configuration.
  cfg=Debug
  if (cd apple && xcodebuild -project Distavo.xcodeproj -scheme "$scheme" -configuration "$cfg" \
        -derivedDataPath "$OUT/$edition" CODE_SIGNING_ALLOWED=NO build >"$OUT/$edition.log" 2>&1); then
    ok "$edition builds unsigned ($scheme)"
  else
    fail "$edition build failed; tail of log:"; tail -15 "$OUT/$edition.log"; continue
  fi
  APP="$(find "$OUT/$edition/Build/Products" -maxdepth 2 -name 'Distavo.app' | head -1)"
  [[ -n "$APP" ]] || { fail "$edition: no Distavo.app in products"; continue; }
  if [[ "$edition" == Direct ]]; then
    [[ -d "$APP/Contents/Frameworks/Sparkle.framework" ]] && ok "Direct links Sparkle" || fail "Direct lost Sparkle"
  else
    [[ -d "$APP/Contents/Frameworks/Sparkle.framework" ]] && fail "$edition contains Sparkle.framework" || ok "$edition has no Sparkle.framework"
  fi
  if [[ "$edition" == AppStore ]]; then
    BIN="$APP/Contents/MacOS/Distavo"
    # strings to a file first: under pipefail, `strings | grep -q` exits 141 (SIGPIPE) exactly when
    # grep FINDS the string early, which used to print "ok" for a binary that contains it.
    STR="$OUT/$edition.strings.txt"
    strings -a "$BIN" >"$STR"
    grep -qi "lemonsqueezy" "$STR" && fail "AppStore binary mentions lemonsqueezy" || ok "AppStore binary: no Lemon Squeezy donate link"
    grep -q "Run in Terminal" "$STR" && fail "AppStore binary has the Run in Terminal helper" || ok "AppStore binary: no Run in Terminal helper"
  fi
done

echo "== $FAILS failure(s)"
[[ $FAILS -eq 0 ]]
